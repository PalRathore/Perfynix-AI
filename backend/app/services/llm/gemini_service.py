@dataclass
class LLMRemediationResult:
    """Structured remediation response generated by Gemini or Fallback engine."""

    cwe_id: str
    finding_title: str
    priority_label: str
    summary: str
    impact: str
    remediation_steps: str
    code_example: str
    source: str  # "gemini-llm" or "template-fallback"

    def to_dict(self) -> dict:
        return asdict(self)


class GeminiLLMService:
    """Generates plain-English XAI remediation plans via Gemini LLM with template fallbacks."""

    def __init__(self) -> None:
        self.api_key = settings.GEMINI_API_KEY
        self.model = None
        self._init_client()

    def _init_client(self) -> None:
        """Initialize Google Gemini API client if API key is provided."""
        if self.api_key:
            try:
                genai.configure(api_key=self.api_key)
                self.model = genai.GenerativeModel("gemini-2.5-flash")
                logger.info("Initialized Google Gemini LLM Service")
            except Exception as exc:  # noqa: BLE001
                logger.warning(f"Failed to initialize Gemini API client: {exc}")

    def generate_remediation(
        self,
        finding_title: str,
        cwe_id: str,
        priority_label: str,
        explanation: str = "",
    ) -> LLMRemediationResult:
        """
        Generate natural language remediation advice.

        Args:
            finding_title: Title of the finding (e.g. "SQL Injection").
            cwe_id: Standard CWE identifier (e.g. "CWE-89").
            priority_label: Predicted priority ("CRITICAL", "HIGH", etc.).
            explanation: Additional context or metric driver details.

        Returns:
            LLMRemediationResult populated by Gemini API or pre-written template.
        """
        # Attempt Gemini API generation if client is active
        if self.model is not None:
            try:
                prompt = (
                    f"You are a cybersecurity expert. Generate a concise remediation guide for:\n"
                    f"- Title: {finding_title}\n"
                    f"- CWE ID: {cwe_id}\n"
                    f"- Priority Level: {priority_label}\n"
                    f"- Context: {explanation}\n\n"
                    f"Provide:\n"
                    f"1. Executive Summary (1-2 sentences)\n"
                    f"2. Potential Impact\n"
                    f"3. Step-by-Step Remediation\n"
                    f"4. Code Example"
                )
                response = self.model.generate_content(prompt)
                if response and response.text:
                    return LLMRemediationResult(
                        cwe_id=cwe_id,
                        finding_title=finding_title,
                        priority_label=priority_label,
                        summary=f"Gemini AI Analysis for {finding_title} ({cwe_id})",
                        impact=f"Priority {priority_label} vulnerability requiring remediation.",
                        remediation_steps=response.text[:1500],
                        code_example="// See AI generated step-by-step guidance above.",
                        source="gemini-llm",
                    )
            except Exception as exc:  # noqa: BLE001
                logger.warning(f"Gemini API call failed: {exc}. Falling back to template engine.")

        # Fallback Engine Execution
        template = CWE_FALLBACK_TEMPLATES.get(cwe_id, GENERIC_FALLBACK_TEMPLATE)
        return LLMRemediationResult(
            cwe_id=cwe_id,
            finding_title=finding_title,
            priority_label=priority_label,
            summary=template["summary"],
            impact=template["impact"],
            remediation_steps=template["remediation_steps"],
            code_example=template["code_example"],
            source="template-fallback",
        )


gemini_service = GeminiLLMService()
